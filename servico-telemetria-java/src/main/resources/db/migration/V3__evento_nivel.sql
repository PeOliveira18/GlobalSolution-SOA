CREATE TABLE OT_EVENTO_NIVEL (
    ID                NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    SENSOR_ID         NUMBER(19)    NOT NULL,
    FAIXA             VARCHAR2(12)  NOT NULL,
    VALOR_DISPARO     NUMBER(7,2)   NOT NULL,
    INICIADO_EM       TIMESTAMP(6)  NOT NULL,
    ENCERRADO_EM      TIMESTAMP(6),
    ALERTA_CIDADAO_ID NUMBER(19),
    NOTIFICADO        NUMBER(1)     DEFAULT 0 NOT NULL,
    CONSTRAINT OT_EVENTO_NIVEL_PK PRIMARY KEY (ID),
    CONSTRAINT OT_EVENTO_NIVEL_SENSOR_FK FOREIGN KEY (SENSOR_ID) REFERENCES OT_SENSOR (ID),
    CONSTRAINT OT_EVENTO_NIVEL_FAIXA_CK CHECK (FAIXA IN ('ATENCAO', 'ALERTA', 'EMERGENCIA')),
    CONSTRAINT OT_EVENTO_NIVEL_NOTIF_CK CHECK (NOTIFICADO IN (0, 1)),
    CONSTRAINT OT_EVENTO_NIVEL_PERIODO_CK CHECK (ENCERRADO_EM IS NULL OR ENCERRADO_EM >= INICIADO_EM)
);

CREATE INDEX OT_EVENTO_NIVEL_SENSOR_IX ON OT_EVENTO_NIVEL (SENSOR_ID, ENCERRADO_EM);
