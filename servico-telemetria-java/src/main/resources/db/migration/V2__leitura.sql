CREATE TABLE OT_LEITURA (
    ID              NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    SENSOR_ID       NUMBER(19)    NOT NULL,
    VALOR           NUMBER(7,2)   NOT NULL,
    UNIDADE         VARCHAR2(5)   NOT NULL,
    FAIXA_CALCULADA VARCHAR2(12)  NOT NULL,
    REGISTRADA_EM   TIMESTAMP(6)  NOT NULL,
    CONSTRAINT OT_LEITURA_PK PRIMARY KEY (ID),
    CONSTRAINT OT_LEITURA_SENSOR_FK FOREIGN KEY (SENSOR_ID) REFERENCES OT_SENSOR (ID),
    CONSTRAINT OT_LEITURA_UNIDADE_CK CHECK (UNIDADE IN ('CM', 'MM_H')),
    CONSTRAINT OT_LEITURA_FAIXA_CK CHECK (FAIXA_CALCULADA IN ('NORMAL', 'ATENCAO', 'ALERTA', 'EMERGENCIA')),
    CONSTRAINT OT_LEITURA_VALOR_CK CHECK (VALOR >= 0)
);

CREATE INDEX OT_LEITURA_SENSOR_DATA_IX ON OT_LEITURA (SENSOR_ID, REGISTRADA_EM);
