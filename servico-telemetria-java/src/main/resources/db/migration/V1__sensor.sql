CREATE TABLE OT_SENSOR (
    ID                   NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    CODIGO               VARCHAR2(40)  NOT NULL,
    TIPO                 VARCHAR2(10)  NOT NULL,
    LATITUDE             NUMBER(9,6)   NOT NULL,
    LONGITUDE            NUMBER(9,6)   NOT NULL,
    ALTURA_INSTALACAO_CM NUMBER(7,2),
    LIMITE_ATENCAO       NUMBER(7,2)   NOT NULL,
    LIMITE_ALERTA        NUMBER(7,2)   NOT NULL,
    LIMITE_EMERGENCIA    NUMBER(7,2)   NOT NULL,
    STATUS               VARCHAR2(12)  DEFAULT 'ATIVO' NOT NULL,
    AREA_RISCO_ID        NUMBER(19)    NOT NULL,
    CONSTRAINT OT_SENSOR_PK PRIMARY KEY (ID),
    CONSTRAINT OT_SENSOR_CODIGO_UK UNIQUE (CODIGO),
    CONSTRAINT OT_SENSOR_TIPO_CK CHECK (TIPO IN ('NIVEL', 'CHUVA')),
    CONSTRAINT OT_SENSOR_STATUS_CK CHECK (STATUS IN ('ATIVO', 'MANUTENCAO', 'INATIVO')),
    CONSTRAINT OT_SENSOR_LATITUDE_CK CHECK (LATITUDE BETWEEN -90 AND 90),
    CONSTRAINT OT_SENSOR_LONGITUDE_CK CHECK (LONGITUDE BETWEEN -180 AND 180),
    CONSTRAINT OT_SENSOR_LIMITES_CK CHECK (LIMITE_ATENCAO < LIMITE_ALERTA AND LIMITE_ALERTA < LIMITE_EMERGENCIA),
    CONSTRAINT OT_SENSOR_ALTURA_CK CHECK (TIPO <> 'NIVEL' OR ALTURA_INSTALACAO_CM > 0)
);
